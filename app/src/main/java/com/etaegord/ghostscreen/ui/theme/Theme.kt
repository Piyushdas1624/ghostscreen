/**
 * M3 Expressive Shape System
 * The GhostScreen identity is defined by pill-shaped (maximum roundedness) geometry.
 * Every interactive container uses fully rounded or generously rounded corners.
 */
val GhostScreenShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),   // sm: chips, small tags
    small = RoundedCornerShape(16.dp),       // DEFAULT: input fields, small cards
    medium = RoundedCornerShape(24.dp),      // md: medium cards, sections
    large = RoundedCornerShape(32.dp),       // lg: large cards, bento items
    extraLarge = RoundedCornerShape(48.dp),  // xl: hero containers
)

@Composable
fun GhostScreenTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) GhostScreenDarkColorScheme else GhostScreenLightColorScheme

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            // Set status bar and nav bar to be transparent for edge-to-edge
            window.statusBarColor = Color.Transparent.toArgb()
            window.navigationBarColor = Color.Transparent.toArgb()
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = GhostScreenTypography,
        shapes = GhostScreenShapes,
        content = content
    )
}
